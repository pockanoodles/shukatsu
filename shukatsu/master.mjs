const ENGINE = dirname(dirname(fileURLToPath(import.meta.url)));
const PROVENANCE = new Set(['V', 'M', 'U', 'T', 'E', 'C', '?']);
const BULLET_SECTIONS = new Set(['work', 'projects', 'volunteering']);
const DEFAULT_SECTION = { experiences: 'work', projects: 'projects', education: 'education' };
const JA_HEADINGS = {
  summary: '概要', work: '職務経歴', projects: 'プロジェクト', education: '学歴',
  certifications: '資格', volunteering: '課外活動', skills: 'スキル',
};
const MATCH = 0.4;   // trace: at or above this a line is that fact
const WEAK = 0.25;   // trace: between WEAK and MATCH it is reported for a human look
const GENERATED = '<!-- Generated by shukatsu/master.mjs from data/career-profile.yml. Edit the profile, then run: node shukatsu/master.mjs render --write -->';

// ---------------------------------------------------------------- loading

export function loadProfile(root) {
  const path = join(root, 'data', 'career-profile.yml');
  if (!existsSync(path)) throw new Error(`No master profile at ${path}`);
  const p = yaml.load(readFileSync(path, 'utf-8'));
  p._path = path;
  p._entities = [];
  p._facts = new Map();
  for (const key of ['experiences', 'projects', 'education']) {
    for (const e of p[key] || []) {
      e.section ??= DEFAULT_SECTION[key];
      e._key = key;
      p._entities.push(e);
      for (const f of e.facts || []) p._facts.set(f.id, { fact: f, entity: e, kind: 'bullet' });
    }
  }
  for (const key of ['summary', 'certifications', 'skills']) {
    for (const f of p[key] || []) p._facts.set(f.id, { fact: f, entity: null, kind: key });
  }
  return p;
}

const isActive = (f) => (f.status ?? 'active') === 'active';
const isVerified = (x) => (x.review_status ?? 'verified') === 'verified';
export const isLive = (f) => isActive(f) && isVerified(f);
const entityLive = (e) => isVerified(e);

// ---------------------------------------------------------------- text tools

export function numbers(text) {
  return (String(text).normalize('NFKC').match(/\d+(?:,\d{3})*(?:\.\d+)?/g) || [])
    .map((n) => n.replace(/,/g, '')).sort();
}

const sameNumbers = (a, b) => JSON.stringify(numbers(a)) === JSON.stringify(numbers(b));

const STOP = new Set(('a an and the of to for in on at by with from as that this which so or its it is are was were be been '
  + 'into than then their his her he they them each every any all before after across per via vs who when where how').split(' '));
// Words every JD and every bullet share. They say nothing about fit.
const JD_GENERIC = new Set(['team', 'work', 'while', 'week', 'develop', 'creat', 'engineer', 'check', 'pay', 'event',
  'design', 'build', 'built', 'help', 'make', 'new', 'able', 'also', 'more', 'other', 'our', 'your', 'you', 'will', 'can',
  'using', 'use', 'role', 'experience', 'strong', 'skill', 'ability', 'including', 'within', 'company'].map((w) => (w.length > 5 ? w.replace(/(ing|ed|es|s)$/, '') : w)));
const stem = (w) => (w.length > 5 ? w.replace(/(ing|ed|es|s)$/, '') : w);

export function tokens(text) {
  const t = String(text).normalize('NFKC').toLowerCase().replace(/\*\*/g, '');
  if (/[぀-ヿ一-鿿]/u.test(t)) {
    const s = t.replace(/[\s\p{P}\p{S}]/gu, '');
    const out = new Set();
    for (let i = 0; i < s.length - 1; i++) out.add(s.slice(i, i + 2));
    return out;
  }
  return new Set((t.match(/[a-z][a-z0-9+#-]*/g) || []).filter((w) => w.length > 2 && !STOP.has(w)).map(stem));
}

export function similarity(line, factText) {
  const a = tokens(line);
  const b = tokens(factText);
  if (!a.size || !b.size) return 0;
  let inter = 0;
  for (const w of b) if (a.has(w)) inter++;
  const jaccard = inter / (a.size + b.size - inter);
  const contained = b.size >= 3 ? 0.9 * (inter / b.size) : 0;
  return Math.max(jaccard, contained);
}

const slug = (s) => String(s).normalize('NFKC').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40) || 'x';
const today = () => new Date().toISOString().slice(0, 10);

// Every wording a fact has been written in: canonical, variants, Japanese.
function forms(f) {
  const out = [{ form: 'text', text: f.text, verified: isVerified(f) }];
  for (const v of f.variants || []) out.push({ form: `variant:${v.key}`, text: v.text, verified: isVerified(v) });
  if (f.ja?.text) out.push({ form: 'ja', text: f.ja.text, verified: isVerified(f.ja) });
  return out;
}

// ---------------------------------------------------------------- render

function headerLines(p, lang) {
  const c = p.candidate || {};
  const labels = [['Location', 'location'], ['Email', 'email'], ['Phone', 'phone'], ['LinkedIn', 'linkedin'],
    ['GitHub', 'github'], ['Availability', 'availability']];
  return [`# CV -- ${c.name}`, '', ...labels.filter(([, k]) => c[k]).map(([l, k]) => `**${l}:** ${c[k]}`)];
}

function factText(f, lang, variant) {
  if (lang === 'ja') return f.ja?.text && isVerified(f.ja) ? f.ja.text : null;
  if (variant) {
    const v = (f.variants || []).find((x) => x.key === variant);
    if (v) return v.text;
  }
  return f.text;
}

/**
 * Render a CV in cv.md's format. `pick` is null for the full render (every live
 * fact, profile order), or a Map entityId -> [{id, variant}] in bullet order.
 */
export function render(p, { pick = null, lang = 'en', summaryId = null } = {}) {
  const skipped = [];
  const out = [...headerLines(p, lang), ''];
  const section = (name, heading, lines) => {
    if (!lines.length) return;
    out.push(`## ${lang === 'ja' ? (JA_HEADINGS[name] || heading) : heading}`, '', ...lines, '');
  };
  const line = (f, variant) => {
    const t = factText(f, lang, variant);
    if (t == null) skipped.push(f.id);
    return t;
  };

  for (const { section: name, heading } of p.layout) {
    if (name === 'summary') {
      const live = (p.summary || []).filter(isLive);
      const s = live.find((x) => x.id === summaryId) || live[0];
      const t = s && line(s);
      section(name, heading, t ? [t] : []);
    } else if (name === 'certifications') {
      section(name, heading, (p.certifications || []).filter(isLive).map((f) => line(f)).filter(Boolean).map((t) => `- ${t}`));
    } else if (name === 'skills') {
      section(name, heading, (p.skills || []).filter(isLive).map((f) => `- **${f.group}:** ${f.text}`));
    } else {
      const lines = [];
      for (const e of p._entities.filter((x) => x.section === name && entityLive(x))) {
        let chosen;
        if (pick) {
          if (!pick.has(e.id)) continue;
          chosen = pick.get(e.id).map(({ id, variant }) => [p._facts.get(id).fact, variant]);
        } else chosen = (e.facts || []).filter(isLive).map((f) => [f, null]);
        const ja = lang === 'ja' ? e.ja || {} : {};
        lines.push(`### ${ja.org || e.heading}`, '');
        const head = [];
        if (e.title) head.push(ja.title ? `**${ja.title}**` : `**${e.title}**${e.title_suffix || ''}`);
        if (e.dates) head.push(e.dates);
        if (head.length) lines.push(...head, '');
        const bullets = chosen.map(([f, v]) => line(f, v)).filter(Boolean).map((t) => `- ${t}`);
        if (bullets.length) lines.push(...bullets, '');
      }
      while (lines.at(-1) === '') lines.pop();
      section(name, heading, lines);
    }
  }
  while (out.at(-1) === '') out.pop();
  return { text: `${out.join('\n')}\n`, skipped };
}

// ---------------------------------------------------------------- select

function scoreFact(f, e, arch, jd) {
  let s = 0;
  const why = [];
  const tags = f.tags || e?.tags || [];
  arch.tags.forEach((t, i) => { if (tags.includes(t)) { s += 3 - i; why.push(`${t}+${3 - i}`); } });
  if (jd.size) {
    const hits = [...tokens(f.text)].filter((w) => jd.has(w) && !JD_GENERIC.has(w));
    const k = Math.min(hits.length, 4);
    if (k) { s += k; why.push(`jd+${k} (${hits.slice(0, 4).join(', ')})`); }
  }
  const pr = f.priority ?? 2;
  s += (3 - pr) * 1.5;
  if (pr !== 2) why.push(`priority ${pr}`);
  if (f.pin) { s += 100; why.push('pinned'); }
  return { score: Math.round(s * 10) / 10, why: why.join(', ') };
}

export function select(p, { archetype, jdText = '' }) {
  const arch = p.archetypes?.[archetype];
  if (!arch) throw new Error(`Unknown archetype "${archetype}". Known: ${Object.keys(p.archetypes || {}).join(', ')}`);
  const cfg = p.select || {};
  const jd = jdText ? tokens(jdText) : new Set();

  const cands = [];
  for (const e of p._entities.filter((x) => BULLET_SECTIONS.has(x.section) && entityLive(x))) {
    for (const f of (e.facts || []).filter(isLive)) {
      const v = (f.variants || []).find((x) => isVerified(x) && (x.for || []).includes(archetype));
      cands.push({ e, f, variant: v?.key || null, ...scoreFact(f, e, arch, jd) });
    }
  }
  const entityScore = new Map();
  for (const e of new Set(cands.map((c) => c.e))) {
    const top = cands.filter((c) => c.e === e).map((c) => c.score).sort((a, b) => b - a).slice(0, 2);
    entityScore.set(e, top.reduce((a, b) => a + b, 0) + (e.always ? 1000 : 0));
  }
  const ranked = (section) => [...entityScore.keys()].filter((e) => e.section === section)
    .sort((a, b) => entityScore.get(b) - entityScore.get(a));

  const caps = new Map();
  ranked('work').forEach((e, i) => caps.set(e, i === 0 ? cfg.main_role_max ?? 5 : cfg.minor_role_max ?? 2));
  ranked('projects').forEach((e, i) => caps.set(e, i < (cfg.projects_max ?? 2) || e.always ? cfg.project_bullets_max ?? 3 : 0));
  ranked('volunteering').forEach((e) => caps.set(e, cfg.volunteering_max ?? 1));

  const chosen = new Map();
  let total = 0;
  const take = (c) => {
    const list = chosen.get(c.e) || [];
    if (list.length >= (caps.get(c.e) ?? 0) || list.includes(c)) return false;
    chosen.set(c.e, [...list, c]);
    total++;
    return true;
  };
  const byScore = [...cands].sort((a, b) => b.score - a.score);
  // An always-shown entity gets its best fact first, so the budget can't starve it.
  for (const e of [...entityScore.keys()].filter((x) => x.always)) {
    const best = byScore.find((c) => c.e === e);
    if (best) take(best);
  }
  for (const c of byScore) if (total < (cfg.max_bullets ?? 14)) take(c);

  const pick = new Map();
  const manifest = [];
  for (const e of p._entities) {
    const list = (chosen.get(e) || []).sort((a, b) => b.score - a.score);
    if (!list.length) continue;
    pick.set(e.id, list.map((c) => ({ id: c.f.id, variant: c.variant })));
    manifest.push({ entity: e.id, facts: list.map((c) => ({ id: c.f.id, variant: c.variant, score: c.score, why: c.why })) });
  }
  const left = cands.filter((c) => !(chosen.get(c.e) || []).includes(c))
    .sort((a, b) => b.score - a.score).map((c) => ({ id: c.f.id, score: c.score, why: c.why }));
  const summary = (p.summary || []).filter(isLive).find((s) => (s.archetypes || []).includes(archetype));
  return { pick, manifest, left, summaryId: summary?.id || null };
}

// ---------------------------------------------------------------- trace

/** Map every claim-like line of a document to the fact it states, if any. */
export function trace(p, text, file = '', { bullets = false } = {}) {
  // finalize checks achievement bullets only. A sweep of an old resume reads every
  // line long enough to carry a claim, whatever its format.
  const lines = bullets
    ? extractBullets(text, file).map((b) => ({ line: b.line, text: b.text }))
    : text.split('\n').map((t, i) => ({ line: i + 1, text: t.replace(/<[^>]+>/g, ' ').replace(/^\s*[-*•]\s+/u, '').trim() }))
      .filter((l) => [...l.text].length >= 25);
  const pool = [];
  for (const [id, { fact }] of p._facts) for (const fm of forms(fact)) pool.push({ id, fact, ...fm });
  return lines.map((l) => {
    let best = null;
    for (const c of pool) {
      const s = similarity(l.text, c.text);
      if (!best || s > best.score) best = { ...c, score: Math.round(s * 100) / 100 };
    }
    const kind = !best || best.score < WEAK ? 'unmatched' : best.score < MATCH ? 'weak' : 'match';
    return {
      ...l, kind, id: kind === 'unmatched' ? null : best.id, form: best?.form, score: best?.score ?? 0,
      retired: kind === 'match' && !isActive(best.fact),
      live: kind === 'match' && isLive(best.fact),
      numbersOk: kind === 'unmatched' ? null : sameNumbers(l.text, best.text),
      expected: best?.text,
    };
  });
}

// ---------------------------------------------------------------- validate

function checkEvidence(root, ev, where, verified, errors, warns) {
  if (!ev?.source) return;
  const path = isAbsolute(ev.source) ? ev.source : resolve(root, ev.source);
  const push = verified ? errors : warns;
  if (!existsSync(path)) { push.push(`${where}: evidence source missing (${ev.source})`); return; }
  if (!ev.quote) return;
  const text = readText(path);
  if (extname(path).toLowerCase() === '.docx' || !Number.isInteger(ev.line)) {
    if (!text.includes(ev.quote)) push.push(`${where}: quote not found in ${ev.source}`);
    return;
  }
  const lines = text.split('\n');
  if ((lines[ev.line - 1] || '').includes(ev.quote)) return;
  const at = lines.findIndex((l) => l.includes(ev.quote));
  if (at >= 0) warns.push(`${where}: evidence moved to ${ev.source}:${at + 1} (says line ${ev.line})`);
  else push.push(`${where}: quote not found in ${ev.source}`);
}

export function validate(p, root) {
  const errors = [];
  const warns = [];
  const vocab = new Set(p.tag_vocabulary || []);
  const archetypes = new Set(Object.keys(p.archetypes || {}));
  for (const a of Object.values(p.archetypes || {})) for (const t of a.tags) if (!vocab.has(t)) errors.push(`archetype tag "${t}" is not in tag_vocabulary`);
  const rules = loadRules(root);
  const ids = new Set();
  const checkId = (id, where) => {
    if (!/^[a-z0-9-]+(\.[a-z0-9-]+)*$/.test(id || '')) errors.push(`${where}: id "${id}" must be lowercase dotted words`);
    if (ids.has(id)) errors.push(`${where}: duplicate id ${id}`);
    ids.add(id);
  };

  for (const e of p._entities) {
    checkId(e.id, e.id);
    for (const t of e.tags || []) if (!vocab.has(t)) errors.push(`${e.id}: tag "${t}" is not in tag_vocabulary`);
    checkEvidence(root, e.evidence, e.id, isVerified(e), errors, warns);
  }
  for (const [id, { fact: f, entity: e, kind }] of p._facts) {
    checkId(id, id);
    if (e && !id.startsWith(`${e.id}.`)) errors.push(`${id}: fact ids start with their entity id (${e.id}.)`);
    if (f.provenance && !PROVENANCE.has(f.provenance)) errors.push(`${id}: provenance "${f.provenance}" is not one of V M U T E C ?`);
    if (kind === 'bullet' && !f.provenance) errors.push(`${id}: provenance is required`);
    for (const t of f.tags || []) if (!vocab.has(t)) errors.push(`${id}: tag "${t}" is not in tag_vocabulary`);
    const status = f.status ?? 'active';
    if (!['active', 'retired'].includes(status)) errors.push(`${id}: status must be active or retired`);
    if (status === 'retired' && (!f.retired_on || !f.reason)) errors.push(`${id}: a retired fact needs retired_on and reason`);
    checkEvidence(root, f.evidence, id, isLive(f), errors, warns);

    for (const v of f.variants || []) {
      if (!v.key) errors.push(`${id}: a variant needs a key`);
      for (const a of v.for || []) if (!archetypes.has(a)) errors.push(`${id}/${v.key}: unknown archetype "${a}"`);
      if (!sameNumbers(v.text, f.text)) errors.push(`${id}/${v.key}: numbers [${numbers(v.text)}] differ from the fact's [${numbers(f.text)}]`);
    }
    // Japanese counters (2件, 1回, 約200万円) make an exact match too strict, so a
    // JA mismatch is a warning to eyeball, not an error.
    if (f.ja?.text && !sameNumbers(f.ja.text, f.text)) {
      warns.push(`${id}/ja: numbers [${numbers(f.ja.text)}] differ from the fact's [${numbers(f.text)}]`);
    }
    if (kind === 'bullet' && isActive(f) && BULLET_SECTIONS.has(e.section)) {
      for (const fm of forms(f).filter((x) => x.form !== 'ja')) {
        for (const r of lintBullet({ text: fm.text, current: e.ended === false }, rules)) {
          const msg = `${id}${fm.form === 'text' ? '' : `/${fm.form}`}: ${r.rule} -- ${r.message}`;
          (r.severity === 'error' && isLive(f) && fm.verified ? errors : warns).push(msg);
        }
      }
    }
  }

  const cvPath = join(root, 'cv.md');
  if (existsSync(cvPath) && readFileSync(cvPath, 'utf-8') !== withBanner(render(p).text)) {
    warns.push('cv.md differs from the profile render (hand-edited, or the profile changed). Run: render --write');
  }
  return { errors, warns };
}

const withBanner = (text) => `${text}\n${GENERATED}\n`;

function upstreamValidate(path) {
  const r = spawnSync(process.execPath, [join(ENGINE, 'career-profile.mjs'), 'validate', path], { cwd: ENGINE, encoding: 'utf-8' });
  return { ok: r.status === 0, out: (r.stdout + r.stderr).trim() };
}

// ---------------------------------------------------------------- manifests

const manifestDir = (root) => join(root, 'data', 'manifests');

function readManifests(root) {
  const dir = manifestDir(root);
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.json'))
    .map((f) => ({ file: join(dir, f), ...JSON.parse(readFileSync(join(dir, f), 'utf-8')) }));
}

function trackerRows(root) {
  const path = join(root, 'data', 'applications.md');
  if (!existsSync(path)) return new Map();
  const rows = new Map();
  for (const l of readFileSync(path, 'utf-8').split('\n')) {
    const cells = l.split('|').map((c) => c.trim());
    if (/^\d+$/.test(cells[1] || '')) rows.set(cells[1], { company: cells[3], role: cells[4], status: cells[6] });
  }
  return rows;
}

const sentIds = (m) => (m.final?.length ? m.final.map((x) => x.id) : (m.selection || []).flatMap((s) => s.facts.map((f) => f.id)));

// ---------------------------------------------------------------- gates

function runGate(name, script, file, root) {
  const r = spawnSync(process.execPath, [join(ENGINE, script), file], {
    cwd: ENGINE, encoding: 'utf-8', env: { ...process.env, CAREER_OPS_DATA_DIR: root },
  });
  return { name, ok: r.status === 0, out: (r.stdout + r.stderr).trim() };
}

export function finalize(p, root, manifestPath, file) {
  const m = JSON.parse(readFileSync(manifestPath, 'utf-8'));
  const docPath = resolve(root, file || m.output);
  const text = readText(docPath);
  const rows = trace(p, text, docPath, { bullets: true });
  const problems = [];
  for (const r of rows) {
    if (r.kind !== 'match') problems.push(`line ${r.line}: traces to no fact (best ${r.id || '-'} at ${r.score}). Add it to the profile or cut it: "${r.text}"`);
    else if (r.retired) problems.push(`line ${r.line}: ${r.id} is retired: "${r.text}"`);
    else if (!r.live) problems.push(`line ${r.line}: ${r.id} is still needs_review`);
    else if (!r.numbersOk) problems.push(`line ${r.line}: numbers changed from ${r.id} [${numbers(r.expected)}] to [${numbers(r.text)}]`);
  }
  const gates = [
    runGate('bullet-lint', 'shukatsu/bullet-lint.mjs', docPath, root),
    runGate('verify-cv-facts', 'verify-cv-facts.mjs', docPath, root),
    runGate('audit', 'shukatsu/audit-materials.mjs', docPath, root),
  ];
  const ok = !problems.length && gates.every((g) => g.ok);
  m.output = relative(root, docPath);
  m.final = rows.filter((r) => r.kind === 'match').map((r) => ({ id: r.id, form: r.form, score: r.score, text: r.text }));
  m.status = ok ? 'final' : 'draft';
  m.finalized = ok ? today() : null;
  writeFileSync(manifestPath, `${JSON.stringify(m, null, 2)}\n`);
  return { ok, problems, gates, rows };
}

// ---------------------------------------------------------------- CLI

function args(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) {
      const k = argv[i].slice(2);
      out[k] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
    } else out._.push(argv[i]);
  }
  return out;
}

function cli(argv) {
  const root = getCareerOpsRoot();
  const a = args(argv);
  const [cmd, target] = a._;
  if (a['self-test']) return selfTest();
  const p = loadProfile(root);

  if (cmd === 'validate') {
    const up = upstreamValidate(p._path);
    const { errors, warns } = validate(p, root);
    if (!up.ok) errors.unshift(`upstream schema: ${up.out}`);
    for (const w of warns) console.log(`warn   ${w}`);
    for (const e of errors) console.log(`ERROR  ${e}`);
    const live = [...p._facts.values()].filter((x) => isLive(x.fact)).length;
    console.log(`\n${p._facts.size} facts (${live} live), ${errors.length} errors, ${warns.length} warnings`);
    return errors.length ? 1 : 0;
  }

  if (cmd === 'pending') {
    let n = 0;
    for (const e of p._entities.filter((x) => !isVerified(x))) { n++; console.log(`entity  ${e.id}: ${e.heading} | ${e.title || ''} | ${e.dates || ''}`); }
    for (const [id, { fact: f }] of p._facts) {
      if (!isActive(f)) continue;
      if (!isVerified(f)) { n++; console.log(`fact    ${id}: ${f.text}`); }
      for (const v of (f.variants || []).filter((x) => !isVerified(x))) { n++; console.log(`variant ${id}/${v.key} (for ${(v.for || []).join(', ')}): ${v.text}`); }
      if (f.ja?.text && !isVerified(f.ja)) { n++; console.log(`ja      ${id}: ${f.ja.text}`); }
    }
    console.log(`\n${n} items need review. Confirm, edit, or reject each, then set review_status: verified.`);
    return 0;
  }

  if (cmd === 'render') {
    let pick = null;
    let summaryId = null;
    if (a.manifest) {
      const m = JSON.parse(readFileSync(resolve(root, a.manifest), 'utf-8'));
      pick = new Map(m.selection.map((s) => [s.entity, s.facts.map((f) => ({ id: f.id, variant: f.variant }))]));
      summaryId = m.summary || null;
    }
    const { text, skipped } = render(p, { pick, lang: a.lang || 'en', summaryId });
    if (a.write) {
      writeFileSync(join(root, 'cv.md'), withBanner(text));
      console.log(`Wrote ${join(root, 'cv.md')}`);
    } else if (a.out) writeFileSync(resolve(root, a.out), text);
    else process.stdout.write(text);
    if (skipped.length) console.error(`${skipped.length} facts have no verified ${a.lang} text and were left out: ${skipped.join(', ')}`);
    return 0;
  }

  if (cmd === 'select') {
    if (!a.archetype || !a.company || !a.role) throw new Error('select needs --archetype, --company, and --role');
    const jdText = a.jd ? readFileSync(resolve(root, a.jd), 'utf-8') : '';
    const s = select(p, { archetype: a.archetype, jdText });
    const name = `${today()}-${slug(a.company)}-${slug(a.role)}`;
    const out = join('output', 'tailored', `${name}.md`);
    mkdirSync(join(root, 'output', 'tailored'), { recursive: true });
    mkdirSync(manifestDir(root), { recursive: true });
    writeFileSync(join(root, out), render(p, { pick: s.pick, summaryId: s.summaryId }).text);
    const manifest = {
      schema: 1, created: today(), company: a.company, role: a.role, num: a.num ? String(a.num) : null,
      archetype: a.archetype, jd: a.jd || null, lang: 'en', summary: s.summaryId,
      selection: s.manifest, output: out, status: 'draft', final: [],
    };
    const mPath = join(manifestDir(root), `${name}.json`);
    writeFileSync(mPath, `${JSON.stringify(manifest, null, 2)}\n`);
    for (const sec of s.manifest) {
      console.log(sec.entity);
      for (const f of sec.facts) console.log(`  ${String(f.score).padStart(6)}  ${f.id}${f.variant ? ` [${f.variant}]` : ''}  ${f.why}`);
    }
    console.log('left out:');
    for (const f of s.left) console.log(`  ${String(f.score).padStart(6)}  ${f.id}  ${f.why}`);
    console.log(`\ndraft     ${out}\nmanifest  ${relative(root, mPath)}\nNext: reword toward the JD per modes/shukatsu/bullets.md, then finalize.`);
    return 0;
  }

  if (cmd === 'finalize') {
    if (!target) throw new Error('finalize needs a manifest path');
    const r = finalize(p, root, resolve(root, target), a.file);
    for (const x of r.problems) console.log(`TRACE  ${x}`);
    for (const g of r.gates) console.log(`${g.ok ? 'pass' : 'FAIL'}   ${g.name}${g.ok ? '' : `\n${g.out.split('\n').slice(-12).join('\n')}`}`);
    console.log(r.ok ? '\nFinal. Manifest records every fact this resume sends.' : '\nNot final. Fix the above and rerun.');
    return r.ok ? 0 : 1;
  }

  if (cmd === 'trace') {
    if (!target) throw new Error('trace needs a file');
    const path = resolve(root, target);
    const rows = trace(p, readText(path), path);
    for (const r of rows) {
      const flag = r.kind === 'unmatched' ? 'NONE ' : r.retired ? 'RETIRED' : r.kind === 'weak' ? 'weak ' : r.numbersOk ? 'ok   ' : 'NUM≠ ';
      console.log(`${flag}  ${String(r.score).padEnd(4)} ${(r.id || '-').padEnd(34)} ${r.text.slice(0, 90)}`);
    }
    const c = (k) => rows.filter(k).length;
    console.log(`\n${c((r) => r.kind === 'match')} matched, ${c((r) => r.retired)} retired, ${c((r) => r.kind === 'match' && !r.numbersOk)} with changed numbers, ${c((r) => r.kind === 'weak')} weak, ${c((r) => r.kind === 'unmatched')} unmatched`);
    if (a.save) {
      if (!a.company) throw new Error('trace --save needs --company');
      mkdirSync(manifestDir(root), { recursive: true });
      const name = `${a.date || today()}-${slug(a.company)}-${slug(a.role || 'role')}`;
      const m = {
        schema: 1, created: today(), company: a.company, role: a.role || null, num: a.num ? String(a.num) : null,
        sent_on: a.date || null, traced: true, output: relative(root, path), status: 'sent-before-master',
        final: rows.filter((r) => r.kind === 'match').map((r) => ({ id: r.id, form: r.form, score: r.score, text: r.text })),
      };
      writeFileSync(join(manifestDir(root), `${name}.json`), `${JSON.stringify(m, null, 2)}\n`);
      console.log(`saved data/manifests/${name}.json`);
    }
    return 0;
  }

  if (cmd === 'sent') {
    if (!target || !a.on) throw new Error('sent needs a manifest path and --on YYYY-MM-DD');
    const mPath = resolve(root, target);
    const m = JSON.parse(readFileSync(mPath, 'utf-8'));
    if (m.status !== 'final') throw new Error(`${target} is ${m.status}, not final. Run finalize first.`);
    m.sent_on = a.on;
    if (a.num) m.num = String(a.num);
    writeFileSync(mPath, `${JSON.stringify(m, null, 2)}\n`);
    console.log(`${m.company} | ${m.role} marked sent on ${a.on}`);
    return 0;
  }

  if (cmd === 'used') {
    const tracker = trackerRows(root);
    const want = a.retired ? (id) => p._facts.has(id) && !isActive(p._facts.get(id).fact) : (id) => id === target;
    if (!a.retired && !target) throw new Error('used needs a fact id, or --retired');
    let n = 0;
    for (const m of readManifests(root)) {
      const hit = [...new Set(sentIds(m).filter(want))];
      if (!hit.length) continue;
      n++;
      const t = m.num ? tracker.get(m.num) : null;
      const when = m.sent_on || `${m.created} (not sent)`;
      console.log(`${when.padEnd(10)}  ${m.company} | ${m.role || '-'}${m.num ? ` | #${m.num}` : ''}${t ? ` | ${t.status}` : ''}  ->  ${hit.join(', ')}`);
    }
    console.log(`\n${n} application${n === 1 ? '' : 's'}`);
    return 0;
  }

  console.log(readFileSync(fileURLToPath(import.meta.url), 'utf-8').match(/\/\*\*([\s\S]*?)\*\//)[1].replace(/^ \* ?/gm, ''));
  return cmd ? 1 : 0;
}

// ---------------------------------------------------------------- self-test

function selfTest() {
  const assert = (c, m) => { if (!c) { console.error(`FAIL ${m}`); process.exitCode = 1; } else console.log(`ok   ${m}`); };
  assert(JSON.stringify(numbers('from 30 to 350 (3.5×, ~4,000 calls)')) === JSON.stringify(['30', '3.5', '350', '4000'].sort()), 'numbers normalizes commas and sorts');
  assert(sameNumbers('69 of 314 (22%)', '22% of 314, 69 cut'), 'number sets compare regardless of order');
  assert(!sameNumbers('32.5% vs 3.7%', '32% vs 6%'), 'changed numbers are caught');
  assert(similarity('Minor in Computer Science, Concentration in MIS', 'Minor in Computer Science') >= MATCH, 'a short fact inside a longer line matches');
  assert(similarity('Built a Tableau dashboard for leadership', 'Scaled outbound dials from 30 to 350') < WEAK, 'unrelated lines do not match');
  assert(similarity('ダイヤラーの移行を推進し架電数を拡大', 'ダイヤラーと業務ツールの移行2件を自ら要件定義・推進し、架電試行数を拡大') > WEAK, 'Japanese uses character bigrams');
  const p = {
    candidate: { name: 'T' }, layout: [{ section: 'work', heading: 'Work' }], archetypes: { a: { tags: ['x'] } }, select: { max_bullets: 2 },
    experiences: [{ id: 'e', heading: 'E', facts: [
      { id: 'e.one', text: 'Cut cost 10% on 5 runs', tags: ['x'], review_status: 'verified' },
      { id: 'e.two', text: 'Wrote 3 docs', review_status: 'verified' },
      { id: 'e.old', text: 'Old 9 claim', status: 'retired', review_status: 'verified' },
      { id: 'e.new', text: 'Draft 7 claim', review_status: 'needs_review' }] }],
  };
  const loaded = { ...p, _entities: [], _facts: new Map() };
  for (const e of p.experiences) { e.section = 'work'; loaded._entities.push(e); for (const f of e.facts) loaded._facts.set(f.id, { fact: f, entity: e, kind: 'bullet' }); }
  const full = render(loaded).text;
  assert(full.includes('Cut cost') && !full.includes('Old 9') && !full.includes('Draft 7'), 'render shows live facts only');
  const s = select(loaded, { archetype: 'a' });
  assert(s.manifest[0].facts[0].id === 'e.one', 'select ranks the tag match first');
  return process.exitCode || 0;
}

